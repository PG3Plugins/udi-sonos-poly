"""
Sonos backend for the PG3x Sonos plugin - the device-API layer.

This is the half of the Home Assistant "sonos" integration that does the
actual work: HA's integration is built on the SoCo library
(https://github.com/SoCo/SoCo), and this backend uses the same library the
same way. Only the framework glue differs between the two platforms, and
that glue is generated by ha2pg3.

Conventions:
- A "device" is a soco.SoCo instance.
- discover_devices() returns [{"address", "name", "device"}] dicts.
- poll_device() returns the poll keys used in the descriptor.
- Command functions take (device) or (device, value); values arriving from
  IoX are strings, so numeric conversions happen here.
"""

import re
import soco
import udi_interface
LOGGER = udi_interface.LOGGER

# address -> SoCo instance, refreshed on every discovery. Lets commands
# that reference another speaker (JOIN) resolve it by node address.
REGISTRY = {}

# SoCo play modes, decomposed into the (shuffle, repeat) pair the node
# exposes as separate drivers - same model as HA's media_player entity.
_MODE_FROM_PAIR = {
    (0, 0): "NORMAL",
    (0, 1): "REPEAT_ALL",
    (0, 2): "REPEAT_ONE",
    (1, 0): "SHUFFLE_NORPT",
    (1, 1): "SHUFFLE",
    (1, 2): "SHUFFLE_REPEAT_ONE",
}

_TRANSPORT = {
    "PLAYING": 1,
    "PAUSED_PLAYBACK": 2,
    "STOPPED": 0,
    "TRANSITIONING": 3,
}


def _address_for(uid):
    clean = re.sub(r"[^a-z0-9]", "", uid.lower())
    return "sp" + clean[-10:]


def _shuffle_repeat(play_mode):
    shuffle = 1 if "SHUFFLE" in play_mode else 0
    if "REPEAT_ONE" in play_mode:
        repeat = 2
    elif "REPEAT_ALL" in play_mode or play_mode == "SHUFFLE":
        repeat = 1
    else:
        repeat = 0
    return shuffle, repeat


def _as_int(value, default=0):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return default


# --------------------------------------------------------------- discovery
def discover_devices(params):

    # The plugin config allows multiple subnets to be specified for the
    # discovery process. This list of subnets can be passed to 
    # soco.discover(). TODO: add that ability here.
    seeds = soco.discover(timeout=5) or set()

    # SSDP only ever finds the physical device. Extra zone players that
    # share its IP - the Sonos Amp Multi hosts up to four, on UPnP ports
    # 1400/1500/1600/1700 - are learned from ZoneGroupState via the seed's
    # zone list. Requires soco >= 0.31.5, which keys players by (IP, port)
    # instead of IP alone; on older soco the virtual players overwrite
    # each other and this expansion simply yields the classic behaviour.
    zones = {}
    for seed in seeds:
        members = None
        for attr in ("visible_zones", "all_zones"):
            try:
                members = getattr(seed, attr)
                break
            except Exception:
                continue
        for dev in members or {seed}:
            try:
                zones[dev.uid] = dev
            except Exception:
                continue

    devices = []
    REGISTRY.clear()
    for dev in zones.values():
        try:
            name = dev.player_name
        except Exception:
            continue  # not a usable zone player (e.g. a bridge/boost ghost)
        address = _address_for(dev.uid)
        REGISTRY[address] = dev
        devices.append({"address": address, "name": name, "device": dev})

    # The plugin config allows the user to specify specific individual
    # speakers. Attempt to connect to those directely.
    LOGGER.info('Include user specifiec speakers')
    for speaker in params:
        LOGGER.info('SPEAKER: {}'.format(speaker))
        dev = soco.SoCo(speaker['ip'])
        REGISTRY[speaker['address']] = dev
        devices.append({"address": speaker['address'], "name": speaker['name'], "device": dev})

                        
    devices.sort(key=lambda d: d["name"])
    return devices


# ------------------------------------------------------------------ polling
def poll_device(dev):
    info = dev.get_current_transport_info()
    state = _TRANSPORT.get(info.get("current_transport_state", ""), 0)
    shuffle, repeat = _shuffle_repeat(dev.play_mode)

    source = 0
    try:
        if dev.is_playing_tv:
            source = 3
        elif dev.is_playing_line_in:
            source = 4
        elif dev.is_playing_radio:
            source = 2
        elif state in (1, 2):
            source = 1
    except Exception:
        source = 1 if state in (1, 2) else 0

    track = {}
    try:
        track = dev.get_current_track_info()
    except Exception:
        pass

    grouped = 0
    try:
        grouped = 1 if dev.group and len(dev.group.members) > 1 else 0
    except Exception:
        pass

    cross_fade = 0
    try:
        cross_fade = 1 if dev.cross_fade else 0
    except Exception:
        pass

    return {
        "transport_state": state,
        "volume": dev.volume,
        "muted": 1 if dev.mute else 0,
        "shuffle": shuffle,
        "repeat": repeat,
        "crossfade": cross_fade,
        "source": source,
        "queue_position": _as_int(track.get("playlist_position"), 0),
        "grouped": grouped,
    }


# ----------------------------------------------------------------- commands
def play(dev):
    dev.play()


def pause(dev):
    dev.pause()


def stop(dev):
    dev.stop()


def next_track(dev):
    dev.next()


def previous_track(dev):
    dev.previous()


def set_volume(dev, value):
    dev.volume = max(0, min(100, _as_int(value)))


def volume_up(dev):
    dev.volume = min(100, dev.volume + 5)


def volume_down(dev):
    dev.volume = max(0, dev.volume - 5)


def set_mute(dev, value):
    dev.mute = _as_int(value) == 1


def toggle_mute(dev):
    dev.mute = not dev.mute


def set_shuffle(dev, value):
    _, repeat = _shuffle_repeat(dev.play_mode)
    dev.play_mode = _MODE_FROM_PAIR[(_as_int(value), repeat)]


def set_repeat(dev, value):
    shuffle, _ = _shuffle_repeat(dev.play_mode)
    dev.play_mode = _MODE_FROM_PAIR[(shuffle, _as_int(value))]


def set_crossfade(dev, value):
    dev.cross_fade = _as_int(value) == 1


def join_group(dev, coordinator_address):
    """Join the group whose coordinator is the speaker at the given node
    address (the address of another node in this plugin)."""
    target = REGISTRY.get(str(coordinator_address).strip())
    if target is not None and target is not dev:
        dev.join(target)


def leave_group(dev):
    dev.unjoin()


def play_uri(dev, uri):
    dev.play_uri(str(uri))
